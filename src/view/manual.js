function renderManual(){
  const root = $('#manual-root');
  if(!root) return;
  root.innerHTML = '';
  ['流程','功能'].forEach(group=>{
    root.appendChild(el('div','manual-label', group));
    const row = el('div','catalog-tabs manual-tabs');
    MANUAL_PAGES.filter(p=>p.group===group).forEach(p=>{
      const b = el('button', manualTab===p.id ? 'on' : '', p.name);
      b.type = 'button';
      b.onclick = ()=>{ manualTab = p.id; renderManual(); };
      row.appendChild(b);
    });
    root.appendChild(row);
  });
  const page = MANUAL_PAGES.find(p=>p.id===manualTab) || MANUAL_PAGES[0];
  const card = el('div','card manual-body');
  card.appendChild(el('h3', null, page.title));
  page.sections.forEach(sec=>{
    if(sec.h) card.appendChild(el('h4', null, sec.h));
    sec.paras.forEach(text=>{
      const p = el('p');
      p.textContent = text;
      card.appendChild(p);
    });
  });
  root.appendChild(card);
}
